#!/bin/bash

# This script prints the child pipeline of the SDE in YAML: the shared jobs of 'gitlab-ci/sde-pipeline.yml', then one image job and one test job per platform.
# The platforms are found by name, as 'scripts/list-robot-platforms.bash' lists them, so adding a platform changes nothing here.
#
# Usage: bash ./gitlab-ci/generate-ci-pipeline.bash > <child-pipeline-file>

################################################################################

# Resolve the repository root directory relative to this script.
SDE_ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# List the platforms, found by name.
SDE_CI_PLATFORM_NAMES="$(bash "${SDE_ROOT_DIR}/scripts/list-robot-platforms.bash")"

################################################################################

# Print the header and the shared jobs.
echo "# Child pipeline of the SDE, generated by 'gitlab-ci/generate-ci-pipeline.bash'."
echo ""
echo "include:"
echo "  - local: gitlab-ci/sde-pipeline.yml"

# Print the image job and the test job of every platform.
for SDE_PLATFORM_NAME in ${SDE_CI_PLATFORM_NAMES}; do
  echo ""
  echo "build-${SDE_PLATFORM_NAME}-image-job:"
  echo "  extends: .build-platform-image"
  echo "  variables:"
  echo "    SDE_ROBOT_PLATFORM: ${SDE_PLATFORM_NAME}"
  echo ""
  echo "test-${SDE_PLATFORM_NAME}-workspaces-job:"
  echo "  extends: .test-catkin-workspaces"
  echo "  needs:"
  echo "    - build-${SDE_PLATFORM_NAME}-image-job"
  echo "  variables:"
  echo "    SDE_ROBOT_PLATFORM: ${SDE_PLATFORM_NAME}"
done

# Print the publish job, which waits for every image and every test.
echo ""
echo "publish-images-job:"
echo "  extends: .publish-images"
echo "  needs:"
echo "    - build-base-image-job"
for SDE_PLATFORM_NAME in ${SDE_CI_PLATFORM_NAMES}; do
  echo "    - build-${SDE_PLATFORM_NAME}-image-job"
  echo "    - test-${SDE_PLATFORM_NAME}-workspaces-job"
done
echo "  variables:"
echo "    SDE_CI_PLATFORM_IMAGES: \"$(for SDE_PLATFORM_NAME in ${SDE_CI_PLATFORM_NAMES}; do printf '%s-devel ' "${SDE_PLATFORM_NAME}"; done | sed 's/ $//')\""
